let current = 'en';
export const setLang = (l) => { current = l === 'ar' ? 'ar' : 'en'; };
export const lang = () => current;
export const t = (key) => {
  const v = STR[current][key];
  return v === undefined ? STR.en[key] : v;
};
/** Pick a bilingual {en, ar} value in the current language with fallback. */
export const loc = (v, l = current) => (v == null ? '' : typeof v === 'string' ? v : v[l] || v.en || v.ar || '');

/** Apply translations to static markup: data-i18n (text), data-i18n-attr="attr:key;attr:key". */
export function applyStatic(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  }
}
